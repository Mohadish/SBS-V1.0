#!/usr/bin/env node
'use strict';

/**
 * SBS Viewer — Per-customer installer orchestrator.
 * =================================================
 * Asks the operator (you) for company ID + display name, bakes them into
 * company.js, runs `npm run build`, renames the resulting installer to
 * include the company slug, then RESTORES company.js to its dev
 * placeholder.
 *
 * USAGE
 *   npm run build:customer
 *     (or: node scripts/build-installer.js)
 *
 * OUTPUT
 *   dist/SBS-Viewer-Setup-<company-slug>-<version>.exe
 *
 * Restoration runs in a try/finally so an interrupted build doesn't leave
 * a customer's company.js sitting in your working tree. company.js IS
 * checked in (with the dev placeholder COMPANY_ID='__DEV__') so fresh
 * clones work without an extra setup step.
 *
 * The backup is whatever the file held when this script STARTED — so if
 * you start from a clean clone or working tree, the dev placeholder is
 * what gets restored. If the script ever crashes between the bake and
 * the finally (e.g. mid-electron-builder), `git status` will surface
 * the still-baked file before you commit. To hand-restore, the canonical
 * dev content is:
 *
 *   'use strict';
 *   module.exports = { COMPANY_ID: '__DEV__', COMPANY_NAME: 'Development' };
 */

const readline    = require('readline');
const fs          = require('fs');
const path        = require('path');
const { spawnSync } = require('child_process');

const PROJECT_ROOT = path.resolve(__dirname, '..');
const COMPANY_PATH = path.join(PROJECT_ROOT, 'company.js');
const DIST_DIR     = path.join(PROJECT_ROOT, 'dist');

// ── Prompt helper ──────────────────────────────────────────────────────
function ask(question) {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  return new Promise(resolve => {
    rl.question(question, answer => {
      rl.close();
      resolve(answer.trim());
    });
  });
}

function _slugify(name) {
  return name
    .normalize('NFKD').replace(/[̀-ͯ]/g, '')   // strip accents
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase()
    .slice(0, 40)
    || 'customer';
}

function _writeCompanyJs(companyId, companyName) {
  // Use JSON.stringify for proper escaping of quotes / specials in either field.
  const content = `'use strict';

/**
 * SBS Viewer — Per-customer baked constants  (generated by build-installer.js)
 *
 * EDIT WITH CARE — this file is overwritten by scripts/build-installer.js
 * during each customer build, and restored to its dev placeholder when the
 * build finishes. Manual edits between builds are harmless; manual edits
 * mid-build will be clobbered.
 */

module.exports = {
  COMPANY_ID:   ${JSON.stringify(companyId)},
  COMPANY_NAME: ${JSON.stringify(companyName)},
};
`;
  fs.writeFileSync(COMPANY_PATH, content, 'utf8');
}

function _readPackageVersion() {
  return require(path.join(PROJECT_ROOT, 'package.json')).version || '0.0.0';
}

(async () => {
  console.log('═══════════════════════════════════════════════════════');
  console.log('  SBS Viewer — Per-customer installer builder');
  console.log('═══════════════════════════════════════════════════════');
  console.log();
  console.log('Two fields, both required:');
  console.log('  Company ID    — opaque identifier baked into the installer.');
  console.log('                  Customer never sees it; it gates license');
  console.log('                  activation. Free-form (any non-empty string).');
  console.log('  Company name  — display name, shown in the activation dialog');
  console.log('                  ("Activate SBS Viewer for Acme Corp").');
  console.log('                  Also drives the installer filename.');
  console.log();

  const companyId   = await ask('Company ID:   ');
  const companyName = await ask('Company name: ');

  if (!companyId)   { console.error('Company ID required. Aborting.');   process.exit(1); }
  if (!companyName) { console.error('Company name required. Aborting.'); process.exit(1); }

  const slug    = _slugify(companyName);
  const version = _readPackageVersion();

  console.log();
  console.log(`[builder] Company ID:   ${companyId}`);
  console.log(`[builder] Company name: ${companyName}`);
  console.log(`[builder] Slug → filename: SBS-Viewer-Setup-${slug}-${version}.exe`);
  console.log();

  const confirm = (await ask('Proceed with build? [Y/n] ')).toLowerCase();
  if (confirm === 'n' || confirm === 'no') {
    console.log('Aborted.');
    process.exit(0);
  }

  // ── Backup current company.js (the dev placeholder) ──────────────────
  let backup;
  try {
    backup = fs.readFileSync(COMPANY_PATH, 'utf8');
  } catch (err) {
    console.error(`[builder] Could not read company.js: ${err.message}`);
    process.exit(1);
  }

  let buildOk = false;
  try {
    // Bake customer values
    _writeCompanyJs(companyId, companyName);
    console.log('[builder] company.js baked.');

    // Run the regular build pipeline (npm run build → bytenode + electron-builder)
    console.log('[builder] running `npm run build`…');
    console.log();
    const res = spawnSync('npm', ['run', 'build'], {
      stdio: 'inherit',
      cwd:   PROJECT_ROOT,
      shell: true,   // needed on Windows for npm.cmd
    });
    if (res.error) {
      console.error('[builder] spawn error:', res.error.message);
      process.exit(1);
    }
    if (res.status !== 0) {
      console.error(`[builder] build failed with exit code ${res.status}`);
      process.exit(res.status || 1);
    }
    buildOk = true;
  } finally {
    // Restore company.js to dev placeholder — always, even on Ctrl+C.
    try {
      fs.writeFileSync(COMPANY_PATH, backup);
      console.log('[builder] company.js restored to dev placeholder.');
    } catch (restoreErr) {
      console.error('[builder] WARNING: could not restore company.js:', restoreErr.message);
      console.error('[builder] Backup content was:\n' + backup);
    }
  }

  if (!buildOk) process.exit(1);

  // ── Rename installer to include the slug ─────────────────────────────
  // electron-builder writes a fixed name ("SBS Viewer Setup <ver>.exe");
  // we rename it post-build to "SBS-Viewer-Setup-<slug>-<ver>.exe".
  // Also handles the portable target if it's produced.
  const renames = [
    { from: `SBS Viewer Setup ${version}.exe`,           to: `SBS-Viewer-Setup-${slug}-${version}.exe` },
    { from: `SBS Viewer Setup ${version}.exe.blockmap`,  to: `SBS-Viewer-Setup-${slug}-${version}.exe.blockmap` },
    { from: `SBS-Viewer-${version}-portable.exe`,        to: `SBS-Viewer-${slug}-${version}-portable.exe` },
  ];
  for (const r of renames) {
    const src = path.join(DIST_DIR, r.from);
    const dst = path.join(DIST_DIR, r.to);
    if (fs.existsSync(src)) {
      try {
        fs.renameSync(src, dst);
        console.log(`[builder] renamed: ${r.to}`);
      } catch (err) {
        console.warn(`[builder] could not rename ${r.from}: ${err.message}`);
      }
    }
  }

  console.log();
  console.log('═══════════════════════════════════════════════════════');
  console.log(`  Customer installer ready for ${companyName}`);
  console.log(`  → dist/SBS-Viewer-Setup-${slug}-${version}.exe`);
  console.log('═══════════════════════════════════════════════════════');
})().catch(err => {
  console.error('[builder] fatal:', err?.stack || err);
  process.exit(1);
});
